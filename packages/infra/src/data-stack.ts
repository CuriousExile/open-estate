/** Attribute and index names of `ApiKeys`, as read by `DynamoDbApiKeyStore` in core. */
export const API_KEYS_PK_ATTRIBUTE = 'keyId';
export const API_KEYS_BY_HASH_INDEX = 'byHash';
export const API_KEYS_HASH_ATTRIBUTE = 'keyHash';

/** Logical SSM values; the parameter name is `/open-estate/<env>/<suffix>` (design: SSM-Parameter). */
export const SSM_PARAMETERS = {
  defaultCurrency: 'default-currency',
  accessMode: 'access-mode',
  rateLimit: 'rate-limit',
  configBucket: 'config-bucket',
  searchProvider: 'search-provider',
  /** Ein/Aus of the Duplikat-Erkennung: `enabled` | `disabled` (duplicate-detection). */
  duplicateDetection: 'duplicate-detection',
} as const;
export type SsmParameterKey = keyof typeof SSM_PARAMETERS;
export type SsmParameterNames = Readonly<Record<SsmParameterKey, string>>;

/** SSM parameter names of an environment; plain strings, known at synth time. */
export function ssmParameterNames(envName: string): SsmParameterNames {
  const names = {} as Record<SsmParameterKey, string>;
  for (const [key, suffix] of Object.entries(SSM_PARAMETERS) as [SsmParameterKey, string][]) {
    names[key] = `/open-estate/${envName}/${suffix}`;
  }
  return names;
}

/**
 * Name of the parameter holding the SPA origin (`https://<distribution domain>`). Owned and
 * written by the FrontendStack, read by the Search_API Lambda: both only use the plain name, so
 * there is no cross-stack reference from the API to the frontend (which depends on the API URL).
 */
export function frontendOriginParameterName(envName: string): string {
  return `/open-estate/${envName}/frontend-origin`;
}

export interface DataStackProps extends StackProps {
  readonly environment: EnvironmentConfig;
  /** Initial SSM values and config directory; default {@link DEFAULT_PLATFORM_SETTINGS}. */
  readonly settings?: PlatformSettings;
}

/**
 * Persistent data and configuration: tables `Listings`, `ApiKeys`, `RateLimitCounters`,
 * `DeletionBlocklist` (shared by import and admin deletion workflow), `DeletionRequests` and
 * `AuditLog` (admin), the private
 * config bucket (seeded from the validated config directory) and the SSM parameters. Physical
 * table/bucket names are generated by CloudFormation; the SSM parameters have fixed names per env.
 */
export class DataStack extends Stack {
  readonly listingsTable: TableV2;
  readonly apiKeysTable: TableV2;
  readonly rateLimitCountersTable: TableV2;
  readonly deletionBlocklistTable: TableV2;
  readonly deletionRequestsTable: TableV2;
  readonly auditLogTable: TableV2;
  readonly configBucket: IBucket;
  /** Validated contents uploaded to the config bucket (e.g. `connectors.json` for ingestion). */
  readonly configFiles: readonly ConfigFile[];
  readonly parameterNames: SsmParameterNames;

  constructor(scope: Construct, id: string, props: DataStackProps) {
    super(scope, id, props);
    const { envName, removalPolicy } = props.environment;
    const settings = props.settings ?? DEFAULT_PLATFORM_SETTINGS;
    const retain = removalPolicy === RemovalPolicy.RETAIN;

    // Validate before creating anything: an invalid taxonomy aborts synth (Req 15.4). The
    // frontend's `i18n-config.json` is mirrored, so API/MCP enable the same locales.
    const configFiles = loadConfigDirectory(settings.configDir, {
      [READ_MODEL_CONFIG_FILES.i18n]: settings.i18nConfigFile,
    });
    this.configFiles = configFiles;

    this.listingsTable = new TableV2(this, 'Listings', {
      partitionKey: { name: 'id', type: AttributeType.STRING },
      // Constant partition key + sort key `id`: ordered, paginated reads for the DynamoDB provider.
      // Sparse: `toListingItem` sets `gsiPk` only for public (`ACTIVE`) listings, so inactive ones
      // are neither found by the DynamoDB provider nor indexed by the stream indexer (Req 6.3).
      globalSecondaryIndexes: [
        {
          indexName: LISTINGS_BY_ID_INDEX,
          partitionKey: { name: LISTINGS_BY_ID_PK_ATTRIBUTE, type: AttributeType.STRING },
          sortKey: { name: 'id', type: AttributeType.STRING },
        },
        // All listings of one data source, for source-based deletion requests (Req 18.4, 18.9).
        {
          indexName: LISTINGS_BY_SOURCE_INDEX,
          partitionKey: { name: 'source', type: AttributeType.STRING },
          sortKey: { name: 'id', type: AttributeType.STRING },
        },
        // Portal lists of one agency, newest change first (Req 2.7). Sparse as well: platform
        // listings without `agencyId` are not part of it.
        {
          indexName: LISTINGS_BY_AGENCY_INDEX,
          partitionKey: { name: LISTINGS_BY_AGENCY_PK_ATTRIBUTE, type: AttributeType.STRING },
          sortKey: { name: LISTINGS_BY_AGENCY_SK_ATTRIBUTE, type: AttributeType.STRING },
        },
      ],
      // Feeds the indexer of the SearchStack; only with OpenSearch, nothing reads it otherwise.
      ...(settings.searchProvider === 'opensearch' && {
        dynamoStream: StreamViewType.NEW_AND_OLD_IMAGES,
      }),
      billing: Billing.onDemand(),
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },
      deletionProtection: retain,
      removalPolicy,
    });

    // Ids removed by a deletion request; the import refuses them (Req 18.6, 18.7). Written by the
    // admin deletion workflow (14.10), read by the import pipeline and the versioned writer. The
    // same key attribute also holds Custom_Id keys `custom#{agencyId}#{customId}` (one key space).
    this.deletionBlocklistTable = new TableV2(this, 'DeletionBlocklist', {
      partitionKey: { name: DELETION_BLOCKLIST_KEY_ATTRIBUTE, type: AttributeType.STRING },
      billing: Billing.onDemand(),
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },
      deletionProtection: retain,
      removalPolicy,
    });

    // Admin deletion requests (Req 18.4, 18.10). The overdue check reads only the table key from
    // `byStatus`, so KEYS_ONLY suffices and keeps criterion and requester out of the index.
    this.deletionRequestsTable = new TableV2(this, 'DeletionRequests', {
      partitionKey: { name: DELETION_REQUESTS_KEY_ATTRIBUTE, type: AttributeType.STRING },
      globalSecondaryIndexes: [
        {
          indexName: DELETION_REQUESTS_BY_STATUS_INDEX,
          partitionKey: {
            name: DELETION_REQUESTS_BY_STATUS_PK_ATTRIBUTE,
            type: AttributeType.STRING,
          },
          sortKey: { name: DELETION_REQUESTS_BY_STATUS_SK_ATTRIBUTE, type: AttributeType.STRING },
          projectionType: ProjectionType.KEYS_ONLY,
        },
      ],
      billing: Billing.onDemand(),
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },
      deletionProtection: retain,
      removalPolicy,
    });

    // Append-only audit trail of admin changes, executed deletions and management operations
    // (Req 17.8, 18.8; management: Req 11).
    this.auditLogTable = new TableV2(this, 'AuditLog', {
      partitionKey: { name: AUDIT_LOG_PARTITION_KEY, type: AttributeType.STRING },
      sortKey: { name: AUDIT_LOG_SORT_KEY, type: AttributeType.STRING },
      // Entries of one agency in time order (Req 11.5); entries without `agencyId` stay out.
      globalSecondaryIndexes: [
        {
          indexName: AUDIT_LOG_BY_AGENCY_INDEX,
          partitionKey: { name: AUDIT_LOG_BY_AGENCY_PK_ATTRIBUTE, type: AttributeType.STRING },
          sortKey: { name: AUDIT_LOG_BY_AGENCY_SK_ATTRIBUTE, type: AttributeType.STRING },
        },
      ],
      billing: Billing.onDemand(),
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },
      deletionProtection: retain,
      removalPolicy,
    });

    this.apiKeysTable = new TableV2(this, 'ApiKeys', {
      partitionKey: { name: API_KEYS_PK_ATTRIBUTE, type: AttributeType.STRING },
      globalSecondaryIndexes: [
        {
          indexName: API_KEYS_BY_HASH_INDEX,
          partitionKey: { name: API_KEYS_HASH_ATTRIBUTE, type: AttributeType.STRING },
        },
      ],
      billing: Billing.onDemand(),
      pointInTimeRecoverySpecification: { pointInTimeRecoveryEnabled: true },
      deletionProtection: retain,
      removalPolicy,
    });

    // Short-lived counters (one item per client and window, removed via TTL): nothing worth
    // backing up or retaining, so no PITR and always disposable.
    this.rateLimitCountersTable = new TableV2(this, 'RateLimitCounters', {
      partitionKey: { name: RATE_LIMIT_COUNTER_KEY_ATTRIBUTE, type: AttributeType.STRING },
      timeToLiveAttribute: RATE_LIMIT_COUNTER_TTL_ATTRIBUTE,
      billing: Billing.onDemand(),
      removalPolicy: RemovalPolicy.DESTROY,
    });

    const configBucket = new Bucket(this, 'ConfigBucket', {
      blockPublicAccess: BlockPublicAccess.BLOCK_ALL,
      objectOwnership: ObjectOwnership.BUCKET_OWNER_ENFORCED,
      encryption: BucketEncryption.S3_MANAGED,
      enforceSSL: true,
      versioned: true,
      removalPolicy,
      autoDeleteObjects: !retain,
    });
    this.configBucket = configBucket;

    // Uploads exactly the validated contents. `prune: false` keeps files that are not part of the
    // config directory (e.g. written later by the admin API); files that are part of it are
    // overwritten on every deployment.
    new BucketDeployment(this, 'ConfigFiles', {
      destinationBucket: configBucket,
      sources: configFiles.map(({ key, content }) => Source.data(key, content)),
      prune: false,
      retainOnDelete: retain,
    });

    this.parameterNames = ssmParameterNames(envName);
    const values: Record<SsmParameterKey, string> = {
      defaultCurrency: settings.defaultCurrency,
      accessMode: settings.accessMode,
      rateLimit: JSON.stringify(settings.rateLimit),
      configBucket: configBucket.bucketName,
      searchProvider: settings.searchProvider,
      duplicateDetection: settings.duplicateDetection,
    };
    for (const key of Object.keys(SSM_PARAMETERS) as SsmParameterKey[]) {
      new StringParameter(this, `${key[0]?.toUpperCase()}${key.slice(1)}Parameter`, {
        parameterName: this.parameterNames[key],
        stringValue: values[key],
        tier: ParameterTier.STANDARD,
      });
    }

    // Read by the seed script (task 3.5) from the stack outputs.
    new CfnOutput(this, 'ListingsTableName', {
      description: 'Physical name of the Listings table',
      value: this.listingsTable.tableName,
    });
    new CfnOutput(this, 'ConfigBucketName', {
      description: 'Physical name of the private config bucket',
      value: configBucket.bucketName,
    });
    // The seed script writes through the import pipeline, which checks the deletion blocklist.
    new CfnOutput(this, 'DeletionBlocklistTableName', {
      description: 'Physical name of the DeletionBlocklist table',
      value: this.deletionBlocklistTable.tableName,
    });
  }
}
